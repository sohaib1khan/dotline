export const LETTERS_AJ = "abcdefghij".split("");
export const LETTERS_AT = "abcdefghijklmnopqrst".split("");
export const LETTERS_AZ = "abcdefghijklmnopqrstuvwxyz".split("");

export function sameDots(a: number[], b: number[]) {
  if (a.length !== b.length) return false;
  const left = [...a].sort((x, y) => x - y);
  const right = [...b].sort((x, y) => x - y);
  return left.every((value, index) => value === right[index]);
}

export function lettersForDifficulty(level: number): string[] {
  if (level >= 4) return LETTERS_AZ;
  if (level >= 3) return LETTERS_AT;
  return LETTERS_AJ;
}
